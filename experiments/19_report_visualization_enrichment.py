"""Stage 16: generate evidence-linked figures and LaTeX visual blocks for reports."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from typing import Any

from common import ensure_dir, load_config, write_csv, write_json
from plotting.report_visuals import save_visual


DEFAULT_CONFIG = "configs/report_visualization_enrichment.yaml"


def run(config_path: str = DEFAULT_CONFIG) -> dict[str, Any]:
    cfg = load_config(config_path)
    output_dir = ensure_dir(cfg.get("output_dir", "results/figures/report_enrichment"))
    block_dir = ensure_dir(cfg.get("latex_block_dir", output_dir / "visual_blocks"))
    manifest: list[dict[str, Any]] = []

    for report in cfg.get("reports", []):
        report_path = report["path"]
        report_slug = Path(report_path).stem
        block_lines = [
            "% Auto-generated by experiments/19_report_visualization_enrichment.py",
            "\\section*{Visual Evidence Gallery}",
        ]
        rendered_figures: list[dict[str, Any]] = []
        for figure in report.get("figures", []):
            figure_id = f"{report_slug}_{figure['figure_id']}"
            png_path = output_dir / f"{figure_id}.png"
            pdf_path = output_dir / f"{figure_id}.pdf"
            save_visual(figure, png_path)
            save_visual(figure, pdf_path)
            caption = figure["caption"]
            rendered_figures.append(
                {
                    **figure,
                    "figure_id": figure_id,
                    "png_path": png_path,
                    "pdf_path": pdf_path,
                    "caption": caption,
                }
            )
            manifest.append(
                {
                    "report_path": report_path,
                    "figure_id": figure_id,
                    "title": figure.get("title", figure_id),
                    "caption": caption,
                    "source_artifact": figure.get("source_artifact", "generated_conceptual"),
                    "png_path": png_path.as_posix(),
                    "pdf_path": pdf_path.as_posix(),
                    "placement": figure.get("placement", "report"),
                    "panel_group": figure.get("panel_group", ""),
                    "orientation": figure.get("orientation", "vertical"),
                }
            )
        block_lines.extend(_render_latex_figures(rendered_figures))
        block_lines.append("\\FloatBarrier")
        (block_dir / f"{report_slug}_visuals.tex").write_text("\n".join(block_lines) + "\n", encoding="utf-8")

    write_csv(output_dir / "figure_manifest.csv", manifest)
    summary = {
        "reports": len(cfg.get("reports", [])),
        "figures": len(manifest),
        "output_dir": output_dir.as_posix(),
        "latex_block_dir": block_dir.as_posix(),
        "does_not_rerun_solver_or_training": True,
    }
    write_json(output_dir / "visualization_summary.json", summary)
    return summary


def _render_latex_figures(figures: list[dict[str, Any]]) -> list[str]:
    lines: list[str] = []
    index = 0
    while index < len(figures):
        figure = figures[index]
        if figure.get("placement") == "inline":
            index += 1
            continue
        panel_group = figure.get("panel_group")
        paired = (
            panel_group
            and not figure.get("force_full_width")
            and index + 1 < len(figures)
            and figures[index + 1].get("panel_group") == panel_group
            and figures[index + 1].get("placement") != "inline"
            and not figures[index + 1].get("force_full_width")
        )
        if paired:
            second = figures[index + 1]
            lines.extend(
                [
                    "\\begin{figure}[!htbp]",
                    "\\centering",
                    *_subfigure_lines(figure),
                    "\\hfill",
                    *_subfigure_lines(second),
                    "\\end{figure}",
                    "",
                ]
            )
            index += 2
            continue

        width = float(figure.get("width", 0.84))
        lines.extend(
            [
                "\\begin{figure}[!htbp]",
                "\\centering",
                f"\\includegraphics[width={width:.2f}\\linewidth]{{{figure['pdf_path'].as_posix()}}}",
                f"\\caption{{{figure['caption']}}}",
                "\\end{figure}",
                "",
            ]
        )
        index += 1
    return lines


def _subfigure_lines(figure: dict[str, Any]) -> list[str]:
    caption = figure.get("panel_caption", figure["caption"])
    return [
        "\\begin{subfigure}[t]{0.48\\linewidth}",
        "\\centering",
        f"\\includegraphics[width=\\linewidth]{{{figure['pdf_path'].as_posix()}}}",
        f"\\caption{{{caption}}}",
        "\\end{subfigure}",
    ]


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default=DEFAULT_CONFIG)
    args = parser.parse_args()
    print(json.dumps(run(args.config), indent=2, sort_keys=True))
